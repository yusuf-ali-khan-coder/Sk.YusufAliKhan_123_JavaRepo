class DataTypes{
	public static void main (String args[]){
		int a=10;
		float b=15.0001f;
		double d=15.9834;
		long c= 10L;
		char ch = 'A';
		boolean bl=true;
		short s=500;
		byte by=10;
		
		System.out.println("int=" + a + "float=" + b);
		System.out.println("long=" + c + "char=" + ch);
		System.out.println("boolean=" + bl + "short=" + s + "byte=" + by);
	}
}
		
		
		